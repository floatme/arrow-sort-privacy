#!/usr/bin/env node
"use strict";

const { execSync } = require("child_process");
const fs = require("fs");
const os = require("os");
const path = require("path");

const tunnelName = process.argv[2] || "aelinkgenerator";
const port = process.argv[3] || "3000";
const domain = "helpmegetaround.com";

function main() {
  let list;
  try {
    list = JSON.parse(execSync("cloudflared tunnel list --output json", { encoding: "utf8" }));
  } catch (err) {
    console.error("Run cloudflared tunnel create first.");
    process.exit(1);
  }

  const tunnel = list.find((t) => t.name === tunnelName);
  if (!tunnel || !tunnel.id) {
    console.error('Tunnel not found: "' + tunnelName + '". Run: cloudflared tunnel create ' + tunnelName);
    process.exit(1);
  }

  const dir = path.join(os.homedir(), ".cloudflared");
  fs.mkdirSync(dir, { recursive: true });

  const credPath = path.join(dir, tunnel.id + ".json");
  if (!fs.existsSync(credPath)) {
    console.error("Missing credentials file:", credPath);
    console.error("Run: cloudflared tunnel login");
    process.exit(1);
  }

  const yaml = [
    "# Auto-generated by scripts/write-cloudflared-config.js",
    "",
    "tunnel: " + tunnel.id,
    "credentials-file: " + credPath.replace(/\\/g, "\\\\"),
    "",
    "ingress:",
    "  - hostname: " + domain,
    "    service: http://127.0.0.1:" + port,
    "  - hostname: www." + domain,
    "    service: http://127.0.0.1:" + port,
    "  - service: http_status:404",
    "",
  ].join("\n");

  const configPath = path.join(dir, "config.yml");
  fs.writeFileSync(configPath, yaml, "utf8");
  console.log("Wrote", configPath);
  console.log("Tunnel ID:", tunnel.id);
}

main();
